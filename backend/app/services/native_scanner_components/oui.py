    # Cache for IEEE OUI database
    _ieee_oui_cache: Dict[str, str] = {}
    _ieee_oui_loaded: bool = False

    @classmethod
    def _load_ieee_oui(cls) -> None:
        """Load IEEE OUI database from arp-scan file (one-time load)."""
        if cls._ieee_oui_loaded:
            return

        # Full IEEE OUI DB (~40k entries) fetched best-effort at install/update by
        # scripts/utils/fetch_oui_db.py into the runtime data tree; falls back to a dev
        # checkout copy, then any system arp-scan/ieee-data file. If none exist, only the
        # small curated OUI_MAP above is used — vendor lookup degrades, never errors.
        data_base = "/opt/EasyPi/data" if os.path.isdir("/opt/EasyPi/data") else "data"
        oui_paths = [
            os.path.join(data_base, "network", "oui.txt.gz"),
            os.path.join(
                os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                "data",
                "oui.txt.gz",
            ),
            "/usr/share/arp-scan/ieee-oui.txt",
            "/usr/local/share/arp-scan/ieee-oui.txt",
            "/var/lib/ieee-data/oui.txt",
        ]

        for oui_path in oui_paths:
            try:
                opener = gzip.open if oui_path.endswith(".gz") else open
                with opener(oui_path, "rt", encoding="utf-8", errors="ignore") as f:
                    for line in f:
                        line = line.strip()
                        if not line or line.startswith("#"):
                            continue
                        # Format: "AABBCC<tab>Vendor Name"
                        parts = line.split("\t", 1)
                        if len(parts) == 2:
                            oui = parts[0].strip().upper()
                            vendor = parts[1].strip()
                            if len(oui) == 6 and vendor:
                                cls._ieee_oui_cache[oui] = vendor
                cls._ieee_oui_loaded = True
                logger.debug(
                    f"Loaded {len(cls._ieee_oui_cache)} OUI entries from {oui_path}"
                )
                return
            except FileNotFoundError:
                continue
            except Exception as e:
                logger.debug(f"Could not load OUI from {oui_path}: {e}")

        cls._ieee_oui_loaded = True  # Mark as loaded even if failed to prevent retries

    @classmethod
    def get_vendor(cls, mac: str) -> Optional[str]:
        """Get vendor name from MAC address."""
        if not mac:
            return None

        # Normalize MAC (remove separators, uppercase)
        normalized = mac.replace(":", "").replace("-", "").replace(".", "").upper()

        if len(normalized) < 6:
            return None

        # Check if this is a locally administered (randomized) MAC address
        # Bit 1 of first octet is 1 for locally administered
        try:
            first_byte = int(normalized[:2], 16)
            if first_byte & 0x02:  # Locally administered bit is set
                return "Private MAC (randomized)"
        except ValueError:
            pass

        # Get OUI (first 6 hex chars)
        oui = normalized[:6]

        # First check built-in database (curated names)
        vendor = cls.OUI_MAP.get(oui)
        if vendor:
            return vendor

        # Fallback to IEEE OUI database
        cls._load_ieee_oui()
        return cls._ieee_oui_cache.get(oui)

    @classmethod
    def get_device_type_hint(cls, vendor: Optional[str]) -> Tuple[Optional[str], float]:
        """Guess device type from vendor with confidence score."""
        if not vendor:
            return None, 0.0

        vendor_lower = vendor.lower()

        # Private/randomized MAC - likely a phone with privacy enabled
        if "private" in vendor_lower or "randomized" in vendor_lower:
            return "phone", 0.60

        # High confidence matches
        if "raspberry pi" in vendor_lower:
            return "sbc", 0.95
        if (
            "playstation" in vendor_lower
            or "xbox" in vendor_lower
            or "nintendo" in vendor_lower
        ):
            return "gaming", 0.90
        if any(x in vendor_lower for x in ["roku", "hisense", "vizio", "tcl"]):
            return "smart-tv", 0.85
        if any(x in vendor_lower for x in ["canon", "hp", "epson", "brother"]):
            return "printer", 0.90
        if any(x in vendor_lower for x in ["synology", "qnap"]):
            return "nas", 0.90
        if any(
            x in vendor_lower
            for x in ["tuya", "shelly", "sonoff", "espressif", "philips hue"]
        ):
            return "iot", 0.85
        if "amazon echo" in vendor_lower:
            return "smart-speaker", 0.90
        if any(
            x in vendor_lower
            for x in ["ubiquiti", "mikrotik", "cisco", "aruba", "zyxel"]
        ):
            return "network", 0.85
        if (
            any(x in vendor_lower for x in ["tp-link", "asus", "d-link"])
            and "smart" not in vendor_lower
        ):
            return "router", 0.70
        if any(x in vendor_lower for x in ["fritz", "avm"]):
            return "router", 0.90
        if any(x in vendor_lower for x in ["apple", "iphone", "ipad", "macbook"]):
            return "apple", 0.80
        if any(x in vendor_lower for x in ["samsung", "oneplus", "oppo", "xiaomi"]):
            return "phone", 0.70
        if "huawei" in vendor_lower:
            return "phone", 0.65  # Could be phone or network equipment
        if "google" in vendor_lower:
            return "google", 0.75
        if any(x in vendor_lower for x in ["vmware", "hyper-v"]):
            return "virtual", 0.95
        if any(x in vendor_lower for x in ["intel", "dell", "realtek"]):
            return "computer", 0.60

        return None, 0.0
