#!/bin/bash
set -Eeuo pipefail

# Remote Tailscale Peer Relay lifecycle used by EasyPi. This script is uploaded
# to the administrator's VPS for one operation and then removed.

TAILSCALE_KEY_FINGERPRINT="2596A99EAAB33821893C0A79458CA832957F5868"
STATE_DIR="/var/lib/easypi-fast-relay"
STATE_FILE="$STATE_DIR/state.env"
LOG_FILE="/var/log/easypi-fast-relay.log"
RELAY_TAG="tag:easypi-relay"

ACTION="${1:-}"
CONFIG_FILE="${2:-}"

[[ $# -eq 2 ]] || { echo "Usage: $0 <deploy|status|restart|disable|uninstall> <config>" >&2; exit 2; }
[[ "$ACTION" =~ ^(deploy|status|restart|disable|uninstall)$ ]] || { echo "Unsupported action" >&2; exit 2; }
[[ -f "$CONFIG_FILE" && ! -L "$CONFIG_FILE" ]] || { echo "Invalid relay configuration" >&2; exit 2; }

umask 077
install -d -o root -g root -m 0700 "$STATE_DIR"
touch "$LOG_FILE"
chown root:root "$LOG_FILE"
chmod 0600 "$LOG_FILE"

log() {
    printf '%s %s\n' "$(date -u '+%Y-%m-%dT%H:%M:%SZ')" "$1" >> "$LOG_FILE"
}

fail() {
    log "ERROR: $1"
    printf 'EASYPI_RELAY_ERROR:%s\n' "$1" >&2
    exit 1
}

cleanup() {
    rm -f -- "$CONFIG_FILE"
}
trap cleanup EXIT

# The file is generated by EasyPi with shell-quoted, validated values and is
# readable only by its SSH user and root. Never log it: it can contain a
# one-time Tailscale authentication key.
# shellcheck disable=SC1090
source "$CONFIG_FILE"

: "${RELAY_NAME:=easypi-fast-relay}"
: "${RELAY_PORT:=40000}"
: "${PUBLIC_ENDPOINT:=}"
: "${AUTH_KEY:=}"

[[ "$RELAY_NAME" =~ ^[a-z0-9][a-z0-9-]{0,62}$ ]] || fail "Invalid relay name"
[[ "$RELAY_PORT" =~ ^[0-9]{1,5}$ ]] || fail "Invalid relay UDP port"
(( RELAY_PORT == 443 || (RELAY_PORT >= 1024 && RELAY_PORT <= 65535) )) \
    || fail "Relay UDP port must be 443 or between 1024 and 65535"
[[ -z "$PUBLIC_ENDPOINT" || "$PUBLIC_ENDPOINT" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}:[0-9]{1,5}$ ]] || fail "Invalid public relay endpoint"
[[ -z "$AUTH_KEY" || "$AUTH_KEY" =~ ^tskey-auth-[A-Za-z0-9_-]{20,480}$ ]] || fail "Invalid Tailscale authentication key"

INSTALLED_BY_EASYPI="false"
FIREWALL_ADDED="false"
ENABLED="false"
SHIELDS_STATE_CAPTURED="false"
PREVIOUS_SHIELDS_UP="false"
SAVED_RELAY_NAME="$RELAY_NAME"
SAVED_RELAY_PORT="$RELAY_PORT"
SAVED_PUBLIC_ENDPOINT="$PUBLIC_ENDPOINT"

load_state() {
    if [[ -f "$STATE_FILE" && ! -L "$STATE_FILE" ]]; then
        # shellcheck disable=SC1090
        source "$STATE_FILE"
    fi
}

save_state() {
    local temporary
    temporary="$(mktemp "$STATE_DIR/.state.XXXXXX")"
    chmod 0600 "$temporary"
    {
        printf 'INSTALLED_BY_EASYPI=%q\n' "$INSTALLED_BY_EASYPI"
        printf 'FIREWALL_ADDED=%q\n' "$FIREWALL_ADDED"
        printf 'ENABLED=%q\n' "$ENABLED"
        printf 'SHIELDS_STATE_CAPTURED=%q\n' "$SHIELDS_STATE_CAPTURED"
        printf 'PREVIOUS_SHIELDS_UP=%q\n' "$PREVIOUS_SHIELDS_UP"
        printf 'SAVED_RELAY_NAME=%q\n' "$SAVED_RELAY_NAME"
        printf 'SAVED_RELAY_PORT=%q\n' "$SAVED_RELAY_PORT"
        printf 'SAVED_PUBLIC_ENDPOINT=%q\n' "$SAVED_PUBLIC_ENDPOINT"
    } > "$temporary"
    mv -f -- "$temporary" "$STATE_FILE"
    chmod 0600 "$STATE_FILE"
}

version_at_least() {
    [[ "$(printf '%s\n%s\n' "$1" "$2" | sort -V | head -n1)" == "$2" ]]
}

install_tailscale() {
    if command -v tailscale >/dev/null 2>&1; then
        return
    fi
    [[ -r /etc/os-release ]] || fail "Only Debian or Ubuntu VPS systems are supported"
    # shellcheck disable=SC1091
    source /etc/os-release
    [[ "${ID:-}" == "debian" || "${ID:-}" == "ubuntu" ]] || fail "Only Debian or Ubuntu VPS systems are supported"
    local codename="${VERSION_CODENAME:-}" repo_family="${ID}"
    [[ "$codename" =~ ^[a-z0-9][a-z0-9.-]{0,31}$ ]] || fail "Could not determine the Linux release codename"

    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq >> "$LOG_FILE" 2>&1
    apt-get install -y -qq ca-certificates curl gnupg >> "$LOG_FILE" 2>&1

    local verify_dir key_file key_fingerprint public_key_count
    verify_dir="$(mktemp -d)"
    chmod 0700 "$verify_dir"
    install -d -m 0700 "$verify_dir/gnupg"
    key_file="$verify_dir/tailscale.gpg"
    curl -fsSL --proto '=https' --proto-redir '=https' \
        "https://pkgs.tailscale.com/stable/${repo_family}/${codename}.noarmor.gpg" -o "$key_file"
    public_key_count="$(GNUPGHOME="$verify_dir/gnupg" gpg --batch --no-options --show-keys --with-colons "$key_file" 2>/dev/null | awk -F: '$1 == "pub" { count++ } END { print count + 0 }')"
    key_fingerprint="$(GNUPGHOME="$verify_dir/gnupg" gpg --batch --no-options --show-keys --with-colons "$key_file" 2>/dev/null | awk -F: '$1 == "fpr" { print $10; exit }')"
    [[ "$public_key_count" == "1" && "$key_fingerprint" == "$TAILSCALE_KEY_FINGERPRINT" ]] || {
        rm -rf -- "$verify_dir"
        fail "Tailscale repository signing key fingerprint mismatch"
    }
    install -o root -g root -m 0644 "$key_file" /usr/share/keyrings/tailscale-archive-keyring.gpg
    rm -rf -- "$verify_dir"
    printf 'deb [signed-by=/usr/share/keyrings/tailscale-archive-keyring.gpg] https://pkgs.tailscale.com/stable/%s %s main\n' "$repo_family" "$codename" > /etc/apt/sources.list.d/tailscale.list
    apt-get update -qq >> "$LOG_FILE" 2>&1
    apt-get install -y -qq tailscale >> "$LOG_FILE" 2>&1
    INSTALLED_BY_EASYPI="true"
}

ensure_json_parser() {
    if command -v python3 >/dev/null 2>&1; then
        return
    fi
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq >> "$LOG_FILE" 2>&1
    apt-get install -y -qq python3-minimal >> "$LOG_FILE" 2>&1 \
        || fail "Python is required to verify the relay identity"
}

ensure_supported_version() {
    local version
    version="$(tailscale version 2>/dev/null | head -n1 | tr -d '[:space:]')"
    [[ "$version" =~ ^[0-9]+\.[0-9]+ ]] || fail "Could not read the Tailscale version"
    version_at_least "$version" "1.86" || fail "Tailscale 1.86 or newer is required for Peer Relay"
}

wait_for_tailscaled() {
    local attempt
    for attempt in $(seq 1 30); do
        if systemctl is-active --quiet tailscaled 2>/dev/null \
            && tailscale status --json >/dev/null 2>&1; then
            return 0
        fi
        sleep 1
    done
    fail "tailscaled did not become ready"
}

relay_has_required_tag() {
    tailscale status --json 2>/dev/null | python3 -c '
import json
import sys

required = sys.argv[1]
try:
    data = json.load(sys.stdin)
except (OSError, ValueError):
    raise SystemExit(1)
self_node = data.get("Self") or {}
tags = self_node.get("Tags") or []
raise SystemExit(0 if required in tags else 1)
' "$RELAY_TAG"
}

ensure_relay_identity() {
    local auth_key_file=""
    if tailscale ip -4 >/dev/null 2>&1; then
        relay_has_required_tag && return
        fail "The existing VPS node is not isolated. Assign tag:easypi-relay to it in Tailscale Machines, then retry"
    fi
    [[ -n "$AUTH_KEY" ]] || fail "This VPS is not signed in to Tailscale; provide a one-time auth key for tag:easypi-relay"
    auth_key_file="$(mktemp /run/easypi-relay-auth.XXXXXX)"
    chmod 0600 "$auth_key_file"
    printf '%s' "$AUTH_KEY" > "$auth_key_file"
    if ! tailscale up --authkey="file:${auth_key_file}" --hostname="$RELAY_NAME" \
        --advertise-tags="$RELAY_TAG" --accept-dns=false >> "$LOG_FILE" 2>&1; then
        rm -f -- "$auth_key_file"
        fail "Tailscale authentication failed"
    fi
    rm -f -- "$auth_key_file"
    AUTH_KEY=""
    relay_has_required_tag || fail "Tailscale connected the VPS without the required tag:easypi-relay identity"
}

shields_up_enabled() {
    tailscale debug prefs 2>/dev/null | grep -Eq '"ShieldsUp"[[:space:]]*:[[:space:]]*true'
}

capture_shields_state() {
    if [[ "$SHIELDS_STATE_CAPTURED" == "true" ]]; then
        return
    fi
    if tailscale debug prefs 2>/dev/null | grep -Eq '"ShieldsUp"[[:space:]]*:[[:space:]]*(true|false)'; then
        shields_up_enabled && PREVIOUS_SHIELDS_UP="true" || PREVIOUS_SHIELDS_UP="false"
        SHIELDS_STATE_CAPTURED="true"
        save_state
        return
    fi
    fail "Could not read the current Tailscale isolation setting"
}

apply_host_isolation() {
    capture_shields_state
    tailscale set --shields-up=true --accept-routes=false --accept-dns=false --ssh=false \
        >> "$LOG_FILE" 2>&1 || fail "Could not isolate the Peer Relay node"
    shields_up_enabled || fail "Tailscale did not enable shields-up isolation"
    relay_has_required_tag || fail "The Peer Relay lost its tag:easypi-relay identity"
}

restore_host_isolation() {
    if [[ "$SHIELDS_STATE_CAPTURED" != "true" ]] || ! command -v tailscale >/dev/null 2>&1; then
        return
    fi
    tailscale set "--shields-up=${PREVIOUS_SHIELDS_UP}" >> "$LOG_FILE" 2>&1 \
        || fail "Could not restore the previous Tailscale isolation setting"
    SHIELDS_STATE_CAPTURED="false"
    PREVIOUS_SHIELDS_UP="false"
}

open_firewall() {
    if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q '^Status: active'; then
        if ! ufw status 2>/dev/null | grep -Eq "^${RELAY_PORT}/udp[[:space:]]+ALLOW"; then
            ufw allow "${RELAY_PORT}/udp" comment 'EasyPi Fast Mobile Relay' >> "$LOG_FILE" 2>&1
            FIREWALL_ADDED="true"
        fi
    fi
}

close_managed_firewall() {
    if [[ "$FIREWALL_ADDED" == "true" ]] && command -v ufw >/dev/null 2>&1; then
        ufw --force delete allow "${SAVED_RELAY_PORT}/udp" >> "$LOG_FILE" 2>&1 || true
    fi
    FIREWALL_ADDED="false"
}

configure_relay() {
    local args=(set "--relay-server-port=${RELAY_PORT}")
    apply_host_isolation
    if [[ "$FIREWALL_ADDED" == "true" && "$SAVED_RELAY_PORT" != "$RELAY_PORT" ]]; then
        close_managed_firewall
    fi
    if [[ -n "$PUBLIC_ENDPOINT" ]]; then
        args+=("--relay-server-static-endpoints=${PUBLIC_ENDPOINT}")
    else
        args+=("--relay-server-static-endpoints=")
    fi
    tailscale "${args[@]}" >> "$LOG_FILE" 2>&1 || fail "Tailscale rejected the Peer Relay settings"
    SAVED_RELAY_NAME="$RELAY_NAME"
    SAVED_RELAY_PORT="$RELAY_PORT"
    SAVED_PUBLIC_ENDPOINT="$PUBLIC_ENDPOINT"
    ENABLED="true"
    open_firewall
    save_state
}

disable_relay() {
    load_state
    if command -v tailscale >/dev/null 2>&1; then
        tailscale set --relay-server-port="" --relay-server-static-endpoints="" >> "$LOG_FILE" 2>&1 \
            || fail "Could not disable the Peer Relay"
    fi
    close_managed_firewall
    restore_host_isolation
    ENABLED="false"
    save_state
}

emit_status() {
    load_state
    local installed="false" daemon="false" version="" tailscale_ip="" listening="false"
    local relay_tagged="false" shields_up="false" isolated="false"
    command -v tailscale >/dev/null 2>&1 && installed="true"
    systemctl is-active --quiet tailscaled 2>/dev/null && daemon="true"
    if [[ "$installed" == "true" ]]; then
        version="$(tailscale version 2>/dev/null | head -n1 | tr -d '[:space:]' || true)"
        tailscale_ip="$(tailscale ip -4 2>/dev/null | head -n1 | tr -d '[:space:]' || true)"
        if command -v python3 >/dev/null 2>&1 && relay_has_required_tag; then relay_tagged="true"; fi
        if shields_up_enabled; then shields_up="true"; fi
        if [[ "$relay_tagged" == "true" && "$shields_up" == "true" ]]; then isolated="true"; fi
    fi
    if [[ "$ENABLED" == "true" ]] && command -v ss >/dev/null 2>&1; then
        ss -H -lun 2>/dev/null | awk '{print $4}' | grep -Eq "(^|:)${SAVED_RELAY_PORT}$" && listening="true" || true
    fi
    printf 'EASYPI_RELAY_RESULT installed=%s daemon=%s enabled=%s listening=%s managed=%s firewall=%s isolated=%s relay_tagged=%s shields_up=%s version=%q tailscale_ip=%q relay_name=%q relay_port=%q public_endpoint=%q\n' \
        "$installed" "$daemon" "$ENABLED" "$listening" "$INSTALLED_BY_EASYPI" "$FIREWALL_ADDED" \
        "$isolated" "$relay_tagged" "$shields_up" "$version" "$tailscale_ip" "$SAVED_RELAY_NAME" "$SAVED_RELAY_PORT" "$SAVED_PUBLIC_ENDPOINT"
}

case "$ACTION" in
    deploy)
        load_state
        install_tailscale
        # Persist package ownership before later steps so a failed first-time
        # deployment can be rolled back without touching a pre-existing install.
        save_state
        systemctl enable --now tailscaled >> "$LOG_FILE" 2>&1 || fail "tailscaled could not be started"
        wait_for_tailscaled
        ensure_supported_version
        ensure_json_parser
        ensure_relay_identity
        configure_relay
        log "Peer Relay enabled on UDP ${RELAY_PORT}"
        emit_status
        ;;
    status)
        emit_status
        ;;
    restart)
        load_state
        [[ -f "$STATE_FILE" ]] || fail "Fast Mobile Relay has not been configured"
        systemctl restart tailscaled >> "$LOG_FILE" 2>&1 || fail "tailscaled could not be restarted"
        wait_for_tailscaled
        RELAY_NAME="$SAVED_RELAY_NAME"
        RELAY_PORT="$SAVED_RELAY_PORT"
        PUBLIC_ENDPOINT="$SAVED_PUBLIC_ENDPOINT"
        ensure_supported_version
        ensure_json_parser
        ensure_relay_identity
        configure_relay
        log "Peer Relay restarted"
        emit_status
        ;;
    disable)
        disable_relay
        log "Peer Relay disabled"
        emit_status
        ;;
    uninstall)
        load_state
        disable_relay
        load_state
        if [[ "$INSTALLED_BY_EASYPI" == "true" ]]; then
            tailscale logout >> "$LOG_FILE" 2>&1 || true
            systemctl disable --now tailscaled >> "$LOG_FILE" 2>&1 || true
            apt-get purge -y -qq tailscale >> "$LOG_FILE" 2>&1 || fail "Could not remove the Tailscale package"
            rm -f /etc/apt/sources.list.d/tailscale.list /usr/share/keyrings/tailscale-archive-keyring.gpg
        fi
        rm -rf -- "$STATE_DIR"
        log "EasyPi Peer Relay configuration removed"
        INSTALLED_BY_EASYPI="false"
        ENABLED="false"
        FIREWALL_ADDED="false"
        emit_status
        ;;
esac
