#!/bin/bash
set -euo pipefail

# Config Restore Script
# Restores a snapshot. Before overwriting anything it takes a pre-restore safety
# snapshot of the CURRENT state. The public invocation schedules a detached
# systemd unit; that unit can quiesce the backend without killing its own runner.

export PATH="/usr/sbin:/usr/bin:/sbin:/bin"
umask 077

if [ $# -ne 1 ]; then
    echo "Usage: $0 <backup_file>" >&2
    exit 1
fi

BACKUP_FILE="$1"
BACKUP_DIR="/opt/EasyPi/backups"
RESTORE_FILE="$BACKUP_FILE"
DECRYPTED_FILE=""
ROLLBACK_FILE=""
PRE_VALIDATION_FILE=""
PRE_SNAPSHOT_DIR=""
PRE=""
RESTORE_STARTED=0
SERVICES_STOPPED=0
POSTGRES_HELPER="/opt/EasyPi/scripts/utils/postgres_backup.py"
SNAPSHOT_HELPER="/opt/EasyPi/scripts/utils/backup_snapshot.py"
POSTGRES_DUMP_REL="opt/EasyPi/data/db/easypi-postgresql.dump"
POSTGRES_DUMP="/${POSTGRES_DUMP_REL}"
STEALTH_STATE_MARKER_REL="opt/EasyPi/data/netprotection/.stealth-state-v1"
STEALTH_STATE_MARKER="/${STEALTH_STATE_MARKER_REL}"
POSTGRES_DUMP_EXTRACTED=0
ARCHIVE_DB_KIND=""
ARCHIVE_HAS_POSTGRES_DUMP=""
ARCHIVE_HAS_STEALTH_POLICY_DIR="no"
ARCHIVE_HAS_STEALTH_STATE_MARKER="no"
CURRENT_DB_KIND=""
RESTORE_STATUS_DIR="/var/lib/easypi/restore-status"
RESTORE_STATUS_FILE="${RESTORE_STATUS_DIR}/latest.json"
declare -a ACTIVE_SERVICES=()
declare -a PRE_SNAPSHOT_ARGS=()
declare -a PRE_STAGED_TARGETS=()

[[ "${EUID}" -eq 0 ]] || {
    echo "ERROR: backup restore must run as root" >&2
    exit 1
}

validate_backup_path() {
    local candidate="$1" canonical name mode

    canonical="$(realpath -e -- "$candidate")" || {
        echo "ERROR: backup does not exist" >&2
        return 1
    }
    name="${canonical##*/}"
    [[ "${canonical%/*}" == "$BACKUP_DIR" ]] || {
        echo "ERROR: backup must be directly under $BACKUP_DIR" >&2
        return 1
    }
    [[ "$name" =~ ^(config|full|pre-restore)-[0-9]{4}-[0-9]{2}-[0-9]{2}-[0-9]{2}-[0-9]{2}(-[0-9]{2})?\.(tar\.gz|epibak)$ ]] || {
        echo "ERROR: backup name is not generated by EasyPi" >&2
        return 1
    }
    [[ -f "$canonical" && ! -L "$canonical" \
        && "$(stat -Lc '%u' -- "$canonical")" == "0" ]] || {
        echo "ERROR: backup must be a root-owned regular file" >&2
        return 1
    }
    mode="$(stat -Lc '%a' -- "$canonical")" || return 1
    (( (8#${mode} & 8#022) == 0 )) || {
        echo "ERROR: backup must not be writable by group or others" >&2
        return 1
    }
    printf '%s\n' "$canonical"
}

BACKUP_FILE="$(validate_backup_path "$BACKUP_FILE")" || exit 1
BACKUP_NAME="${BACKUP_FILE##*/}"

write_restore_status() {
    local status="$1" temporary
    install -d -o root -g easypi -m 0750 "$RESTORE_STATUS_DIR" || return 1
    temporary="$(mktemp "${RESTORE_STATUS_DIR}/.latest.XXXXXX")" || return 1
    printf '{"archive":"%s","status":"%s","updated_at":"%s"}\n' \
        "$BACKUP_NAME" "$status" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" \
        > "$temporary" || { rm -f -- "$temporary"; return 1; }
    chown root:easypi "$temporary" || { rm -f -- "$temporary"; return 1; }
    chmod 0640 "$temporary" || { rm -f -- "$temporary"; return 1; }
    mv -f -- "$temporary" "$RESTORE_STATUS_FILE"
}

if [[ "${EASYPI_RESTORE_DETACHED:-0}" != "1" ]]; then
    command -v systemd-run >/dev/null 2>&1 || {
        echo "ERROR: systemd-run is required for a safe detached restore" >&2
        exit 1
    }
    # Prevent a previous result for the same archive from being mistaken for
    # this new operation while the transient unit is entering the running state.
    rm -f -- "$RESTORE_STATUS_FILE"
    systemd-run --quiet --no-block --collect \
        --unit=easypi-restore \
        --description="EasyPi backup restore" \
        --property=Type=oneshot \
        --property=TimeoutStartSec=6h \
        --property=KillMode=control-group \
        /usr/bin/env -i \
            PATH="/usr/sbin:/usr/bin:/sbin:/bin" \
            EASYPI_RESTORE_DETACHED=1 \
            /bin/bash /opt/EasyPi/scripts/backup/restore_config_backup.sh \
            "$BACKUP_FILE" || {
        echo "ERROR: another restore may already be running or the restore unit could not be scheduled" >&2
        exit 1
    }
    echo "RESTORE_SCHEDULED=easypi-restore.service"
    exit 0
fi

command -v flock >/dev/null 2>&1 || {
    echo "ERROR: flock is required for backup restore" >&2
    exit 69
}
exec 9>/run/easypi-backup.lock
if ! flock -n 9; then
    echo "ERROR: another EasyPi backup or restore operation is running" >&2
    exit 75
fi

# Validate again in the detached process. backup_crypto.py repeats the
# regular-file ownership/mode check when it opens an encrypted source.
BACKUP_FILE="$(validate_backup_path "$BACKUP_FILE")" || exit 1
BACKUP_NAME="${BACKUP_FILE##*/}"

service_was_active() {
    local wanted="$1" active
    for active in "${ACTIVE_SERVICES[@]}"; do
        [[ "$active" == "$wanted" ]] && return 0
    done
    return 1
}

record_and_stop_services() {
    local service
    command -v systemctl >/dev/null 2>&1 || {
        echo "ERROR: systemctl is required for a consistent restore" >&2
        return 1
    }
    ACTIVE_SERVICES=()
    for service in \
        easypi-backend.service \
        easypi-telegram-bot.service \
        easypi-taildrop-import.service \
        easypi-celery.service \
        easypi-stealth-guard.service \
        easypi-stealth-resume.service \
        easypi-stealth-dns.service \
        easypi-netprotection.service \
        easypi-dhcp-observer.service \
        nginx.service; do
        if systemctl is-active --quiet "$service"; then
            ACTIVE_SERVICES+=("$service")
        fi
    done
    SERVICES_STOPPED=1
    for service in "${ACTIVE_SERVICES[@]}"; do
        systemctl stop "$service" || {
            echo "ERROR: could not stop $service for backup restore" >&2
            return 1
        }
    done
}

stop_recorded_services() {
    local service
    for service in "${ACTIVE_SERVICES[@]}"; do
        systemctl stop "$service" >/dev/null 2>&1 || true
    done
    SERVICES_STOPPED=1
}

start_recorded_services() {
    local service
    systemctl daemon-reload || return 1
    # Start dependencies and the web edge before the API-facing services.
    for service in \
        nginx.service \
        easypi-stealth-guard.service \
        easypi-stealth-dns.service \
        easypi-stealth-resume.service \
        easypi-netprotection.service \
        easypi-dhcp-observer.service \
        easypi-backend.service \
        easypi-telegram-bot.service \
        easypi-taildrop-import.service \
        easypi-celery.service; do
        service_was_active "$service" || continue
        systemctl reset-failed "$service" >/dev/null 2>&1 || true
        systemctl start "$service" || return 1
    done
    SERVICES_STOPPED=0
}

backend_health_ok() {
    local attempt code
    local runtime_check="/opt/EasyPi/scripts/maintenance/verify_runtime_health.py"
    service_was_active easypi-backend.service || return 0
    command -v curl >/dev/null 2>&1 || return 1
    for ((attempt = 0; attempt < 90; attempt++)); do
        code="$(curl --silent --output /dev/null --write-out '%{http_code}' \
            --max-time 3 http://127.0.0.1:8000/health 2>/dev/null || printf '000')"
        if [[ "$code" == "200" && -f "$runtime_check" ]] \
            && /usr/bin/python3 "$runtime_check" >/dev/null 2>&1; then
            return 0
        fi
        sleep 2
    done
    [[ -f "$runtime_check" ]] && /usr/bin/python3 "$runtime_check" || true
    return 1
}

validate_database_archive_contract() {
    local archive="$1" kind has_dump
    read -r kind has_dump < <(
        /usr/bin/python3 "$POSTGRES_HELPER" archive-info "$archive"
    ) || return 1
    case "$kind:$has_dump" in
        postgresql:yes|sqlite:no|missing:no) ;;
        postgresql:no)
            echo "ERROR: PostgreSQL backup is incomplete: database dump is missing" >&2
            return 1
            ;;
        sqlite:yes|missing:yes)
            echo "ERROR: backup contains a PostgreSQL dump without PostgreSQL configuration" >&2
            return 1
            ;;
        *)
            echo "ERROR: backup database type is unsupported" >&2
            return 1
            ;;
    esac
    printf '%s %s\n' "$kind" "$has_dump"
}

archive_has_stealth_policy_dir() {
    /usr/bin/python3 - "$1" <<'PY'
import sys
import tarfile

with tarfile.open(sys.argv[1], "r:gz") as archive:
    for member in archive:
        name = member.name
        while name.startswith("./"):
            name = name[2:]
        if name.rstrip("/") == "var/lib/easypi/stealth-policy":
            raise SystemExit(0)
raise SystemExit(1)
PY
}

archive_has_stealth_state_marker() {
    /usr/bin/python3 - "$1" "$STEALTH_STATE_MARKER_REL" <<'PY'
import sys
import tarfile

with tarfile.open(sys.argv[1], "r:gz") as archive:
    for member in archive:
        name = member.name
        while name.startswith("./"):
            name = name[2:]
        if name == sys.argv[2]:
            raise SystemExit(0)
raise SystemExit(1)
PY
}

restore_extracted_database() {
    local kind="$1"
    if [[ "$kind" == "postgresql" ]]; then
        [[ -f "$POSTGRES_DUMP" && ! -L "$POSTGRES_DUMP" ]] || {
            echo "ERROR: validated PostgreSQL dump was not extracted" >&2
            return 1
        }
        POSTGRES_DUMP_EXTRACTED=1
        /opt/EasyPi/backend/.venv/bin/python "$POSTGRES_HELPER" \
            restore "$POSTGRES_DUMP" || return 1
        rm -f -- "$POSTGRES_DUMP"
        POSTGRES_DUMP_EXTRACTED=0
    elif [[ -e "$POSTGRES_DUMP" || -L "$POSTGRES_DUMP" ]]; then
        echo "ERROR: unexpected PostgreSQL dump was extracted" >&2
        return 1
    fi
}

rollback_pre_restore() {
    local rollback_kind rollback_has_dump
    [[ -n "$PRE" && -s "$PRE" && ! -L "$PRE" ]] || return 1
    ROLLBACK_FILE="$(mktemp "${BACKUP_DIR}/.restore.XXXXXX.tar.gz")" || return 1
    /opt/EasyPi/backend/.venv/bin/python \
        /opt/EasyPi/scripts/utils/backup_crypto.py \
        decrypt "$PRE" "$ROLLBACK_FILE" || return 1
    chown root:root "$ROLLBACK_FILE" || return 1
    chmod 600 "$ROLLBACK_FILE" || return 1
    /usr/bin/python3 /opt/EasyPi/scripts/utils/secure_restore.py \
        --validate-only "$ROLLBACK_FILE" >/dev/null || return 1
    read -r rollback_kind rollback_has_dump < <(
        validate_database_archive_contract "$ROLLBACK_FILE"
    ) || return 1
    remove_restore_changes_before_rollback || return 1
    /usr/bin/python3 /opt/EasyPi/scripts/utils/secure_restore.py "$ROLLBACK_FILE" \
        || return 1
    restore_extracted_database "$rollback_kind"
}

remove_restore_changes_before_rollback() {
    # secure_restore.py deliberately overlays a validated archive.  Before an
    # automatic rollback, remove only the fixed scopes the failed operation
    # was allowed to change so files introduced by that operation cannot
    # survive the pre-restore snapshot being reapplied.
    case "$BACKUP_NAME" in
        full-*|pre-restore-*)
            rm -rf -- /opt/EasyPi/config /opt/EasyPi/data
            rm -rf -- /var/lib/easypi/stealth-policy
            ;;
        config-*)
            rm -rf -- /opt/EasyPi/config /opt/EasyPi/data/db
            rm -f -- \
                /opt/EasyPi/data/netprotection/allowlist.txt \
                /opt/EasyPi/data/netprotection/user_blocklist.txt \
                /opt/EasyPi/data/netprotection/blocklist_config.json \
                /opt/EasyPi/data/netprotection/stealth_meta.json \
                /opt/EasyPi/data/netprotection/stealth_client.conf \
                /opt/EasyPi/data/user/mobile_link.json \
                "$STEALTH_STATE_MARKER"
            rm -rf -- /var/lib/easypi/stealth-policy
            ;;
        *)
            echo "ERROR: unknown restore scope for rollback" >&2
            return 1
            ;;
    esac

    # The environment file may have been absent before restore. Removing it
    # first lets absence in the pre-restore snapshot remain meaningful. Host
    # files are never deleted here: /etc/hosts is generic, and the installed
    # kernel, nginx and unbound configuration is not a restore target, so a
    # rollback could not put it back.
    rm -f -- /opt/EasyPi/.env
}

cleanup_restore() {
    local rc=$?
    local rollback_ok=0
    trap - EXIT
    set +e

    if (( rc != 0 && RESTORE_STARTED == 1 )); then
        echo "WARNING: restore failed; rolling back to the pre-restore snapshot" >&2
        stop_recorded_services
        if rollback_pre_restore; then
            rollback_ok=1
            echo "Pre-restore snapshot reapplied." >&2
        else
            echo "ERROR: automatic pre-restore rollback failed; snapshot retained at $PRE" >&2
        fi
    fi

    if (( SERVICES_STOPPED == 1 && !(rc != 0 && RESTORE_STARTED == 1 && rollback_ok == 0) )); then
        if ! start_recorded_services; then
            echo "ERROR: one or more previously active services could not be restarted" >&2
            rc=1
        fi
    elif (( SERVICES_STOPPED == 1 )); then
        echo "ERROR: rollback was incomplete; state-writing services remain stopped" >&2
    fi
    if (( rollback_ok == 1 )) && ! backend_health_ok; then
        echo "ERROR: rollback completed, but backend health did not recover" >&2
        rc=1
        rollback_ok=0
    fi

    [[ -z "$DECRYPTED_FILE" ]] || rm -f -- "$DECRYPTED_FILE"
    [[ -z "$ROLLBACK_FILE" ]] || rm -f -- "$ROLLBACK_FILE"
    [[ -z "$PRE_VALIDATION_FILE" ]] || rm -f -- "$PRE_VALIDATION_FILE"
    if [[ -n "$PRE_SNAPSHOT_DIR" && "$PRE_SNAPSHOT_DIR" == "$BACKUP_DIR"/.pre-snapshot.* ]]; then
        rm -rf -- "$PRE_SNAPSHOT_DIR"
    fi
    if (( POSTGRES_DUMP_EXTRACTED == 1 )); then
        rm -f -- "$POSTGRES_DUMP"
    fi
    if (( rc != 0 && RESTORE_STARTED == 0 )) && [[ -n "$PRE" ]]; then
        rm -f -- "$PRE"
    fi
    if (( rc == 0 )); then
        write_restore_status success || rc=1
    elif (( rollback_ok == 1 )); then
        write_restore_status failed-rolled-back || true
    else
        write_restore_status failed || true
    fi
    exit "$rc"
}
trap cleanup_restore EXIT
write_restore_status running || {
    echo "ERROR: could not publish restore status" >&2
    exit 1
}

case "$BACKUP_FILE" in
    *.epibak)
        install -d -m 750 -o root -g easypi "$BACKUP_DIR"
        DECRYPTED_FILE="$(mktemp "${BACKUP_DIR}/.restore.XXXXXX.tar.gz")"
        /opt/EasyPi/backend/.venv/bin/python \
            /opt/EasyPi/scripts/utils/backup_crypto.py \
            decrypt "$BACKUP_FILE" "$DECRYPTED_FILE"
        chown root:root "$DECRYPTED_FILE"
        chmod 600 "$DECRYPTED_FILE"
        RESTORE_FILE="$DECRYPTED_FILE"
        ;;
    *.tar.gz) ;;
    *) echo "ERROR: unsupported backup format" >&2; exit 1 ;;
esac

# Prove the selected backup is completely readable and inside the restore
# contract before services are stopped or a pre-restore snapshot is created.
/usr/bin/python3 /opt/EasyPi/scripts/utils/secure_restore.py \
    --validate-only "$RESTORE_FILE" >/dev/null
read -r ARCHIVE_DB_KIND ARCHIVE_HAS_POSTGRES_DUMP < <(
    validate_database_archive_contract "$RESTORE_FILE"
)
if archive_has_stealth_policy_dir "$RESTORE_FILE"; then
    ARCHIVE_HAS_STEALTH_POLICY_DIR="yes"
fi
if archive_has_stealth_state_marker "$RESTORE_FILE"; then
    ARCHIVE_HAS_STEALTH_STATE_MARKER="yes"
fi
if [[ "$BACKUP_NAME" == config-* \
      && "$ARCHIVE_HAS_STEALTH_POLICY_DIR" == "yes" \
      && "$ARCHIVE_HAS_STEALTH_STATE_MARKER" != "yes" ]]; then
    echo "ERROR: config backup contains Chameleon policy without its matching metadata" >&2
    exit 1
fi

CURRENT_DB_KIND="$(
    /opt/EasyPi/backend/.venv/bin/python "$POSTGRES_HELPER" kind
)"
case "$CURRENT_DB_KIND" in
    postgresql|sqlite|missing) ;;
    *)
        echo "ERROR: current database type cannot be backed up for safe rollback" >&2
        exit 1
        ;;
esac

echo "Starting config restore from: $BACKUP_FILE"

# Quiesce every EasyPi process that can hold SQLite files or mutate managed
# state. This script is now in its own transient unit, so stopping the backend
# cannot terminate the restore itself.
record_and_stop_services

# Safety net: snapshot the current state first so this restore can be undone.
PRE_STAMP="$(date +%Y-%m-%d-%H-%M-%S)"
PRE="${BACKUP_DIR}/pre-restore-${PRE_STAMP}.epibak"
[[ ! -e "$PRE" && ! -L "$PRE" ]] || {
    echo "ERROR: pre-restore snapshot name collision; retry in one second" >&2
    exit 1
}
PRE_TARGETS=()
PRE_CANDIDATES=(
    /etc/hostname \
    /etc/hosts \
    /opt/EasyPi/.env \
    /opt/EasyPi/config \
    /var/lib/easypi/stealth-policy
)
if [[ "$BACKUP_NAME" == full-* || "$BACKUP_NAME" == pre-restore-* ]]; then
    # A full restore can touch any EasyPi data path, so its safety snapshot must
    # cover the whole current tree for an exact automatic rollback.
    PRE_CANDIDATES+=(/opt/EasyPi/data)
else
    PRE_CANDIDATES+=(
        /opt/EasyPi/data/db
        /opt/EasyPi/data/netprotection/allowlist.txt
        /opt/EasyPi/data/netprotection/user_blocklist.txt
        /opt/EasyPi/data/netprotection/blocklist_config.json
        /opt/EasyPi/data/netprotection/stealth_meta.json
        /opt/EasyPi/data/netprotection/stealth_client.conf
        /opt/EasyPi/data/user/mobile_link.json
    )
fi
for p in "${PRE_CANDIDATES[@]}"; do
    if [ -e "$p" ]; then
        PRE_TARGETS+=("$p")
    fi
done
PRE_SNAPSHOT_DIR="$(mktemp -d "${BACKUP_DIR}/.pre-snapshot.XXXXXX")"
for p in "${PRE_TARGETS[@]}"; do
    PRE_SNAPSHOT_ARGS+=(--source "$p")
    PRE_STAGED_TARGETS+=("${p#/}")
done
PRE_SNAPSHOT_ARGS+=(--exclude "$POSTGRES_DUMP")
/opt/EasyPi/backend/.venv/bin/python "$SNAPSHOT_HELPER" \
    --root "$PRE_SNAPSHOT_DIR" "${PRE_SNAPSHOT_ARGS[@]}"
if [[ "$CURRENT_DB_KIND" == "postgresql" ]]; then
    /opt/EasyPi/backend/.venv/bin/python "$POSTGRES_HELPER" \
        dump "$PRE_SNAPSHOT_DIR/$POSTGRES_DUMP_REL"
    DUMP_COVERED=0
    for p in "${PRE_STAGED_TARGETS[@]}"; do
        if [[ "$POSTGRES_DUMP_REL" == "$p" || "$POSTGRES_DUMP_REL" == "$p"/* ]]; then
            DUMP_COVERED=1
            break
        fi
    done
    (( DUMP_COVERED == 1 )) || PRE_STAGED_TARGETS+=("$POSTGRES_DUMP_REL")
fi
echo "Creating pre-restore safety snapshot: $PRE"
if ! tar -C "$PRE_SNAPSHOT_DIR" -czf - \
        "${PRE_STAGED_TARGETS[@]}" \
        | /opt/EasyPi/backend/.venv/bin/python \
            /opt/EasyPi/scripts/utils/backup_crypto.py \
            encrypt-stdin "$PRE"; then
    rm -f -- "$PRE"
    echo "ERROR: pre-restore safety snapshot failed; restore was not started" >&2
    exit 1
fi
rm -rf -- "$PRE_SNAPSHOT_DIR"
PRE_SNAPSHOT_DIR=""
if [ ! -s "$PRE" ] || ! chown root:easypi "$PRE" || ! chmod 640 "$PRE"; then
    rm -f -- "$PRE"
    echo "ERROR: pre-restore safety snapshot could not be secured; restore was not started" >&2
    exit 1
fi

# Do not enter the destructive phase unless the safety snapshot itself is
# authenticated, fully readable, and accepted by the exact restore validator.
PRE_VALIDATION_FILE="$(mktemp "${BACKUP_DIR}/.restore.XXXXXX.tar.gz")"
/opt/EasyPi/backend/.venv/bin/python \
    /opt/EasyPi/scripts/utils/backup_crypto.py \
    decrypt "$PRE" "$PRE_VALIDATION_FILE" >/dev/null
chown root:root "$PRE_VALIDATION_FILE"
chmod 600 "$PRE_VALIDATION_FILE"
/usr/bin/python3 /opt/EasyPi/scripts/utils/secure_restore.py \
    --validate-only "$PRE_VALIDATION_FILE" >/dev/null
validate_database_archive_contract "$PRE_VALIDATION_FILE" >/dev/null
rm -f -- "$PRE_VALIDATION_FILE"
PRE_VALIDATION_FILE=""
echo "PRE_RESTORE_BACKUP=$PRE"

# The helper verifies canonical location, root ownership, permissions, member
# types and an explicit restore allowlist, then writes through no-follow fds.
echo "Extracting configuration files..."
RESTORE_STARTED=1
rm -f -- "$POSTGRES_DUMP"
# Current backups include this directory even when strict mode is disabled, so
# replacing it gives policy state exact restore semantics. A legacy config-only
# backup did not touch Stealth metadata and therefore preserves current policy;
# a legacy full backup restores metadata and must clear the unmatched policy.
if [[ "$ARCHIVE_HAS_STEALTH_POLICY_DIR" == "yes" \
      || "$BACKUP_NAME" == full-* \
      || "$BACKUP_NAME" == pre-restore-* ]]; then
    rm -rf -- /var/lib/easypi/stealth-policy
fi
if [[ "$ARCHIVE_HAS_STEALTH_STATE_MARKER" == "yes" \
      || "$BACKUP_NAME" == full-* \
      || "$BACKUP_NAME" == pre-restore-* ]]; then
    rm -f -- \
        /opt/EasyPi/data/netprotection/stealth_meta.json \
        /opt/EasyPi/data/netprotection/stealth_client.conf
fi
/usr/bin/python3 /opt/EasyPi/scripts/utils/secure_restore.py "$RESTORE_FILE"
rm -f -- "$STEALTH_STATE_MARKER"
[[ "$ARCHIVE_HAS_POSTGRES_DUMP" != "yes" ]] || POSTGRES_DUMP_EXTRACTED=1
restore_extracted_database "$ARCHIVE_DB_KIND"

start_recorded_services || {
    echo "ERROR: restored services did not start" >&2
    exit 1
}
backend_health_ok || {
    echo "ERROR: backend did not become healthy after restore" >&2
    exit 1
}

echo "Config restore completed successfully!"
