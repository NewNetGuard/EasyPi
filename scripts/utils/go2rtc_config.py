#!/usr/bin/python3
from __future__ import annotations

import grp
import json
import os
import re
import sys
import tempfile
from pathlib import Path
from urllib.parse import urlsplit

MAX_PAYLOAD = 1024 * 1024
NAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9_.-]{0,63}$")


def main() -> None:
    if len(sys.argv) != 2:
        raise SystemExit("usage: go2rtc_config.py <target>")

    raw = sys.stdin.buffer.read(MAX_PAYLOAD + 1)
    if len(raw) > MAX_PAYLOAD:
        raise SystemExit("payload is too large")
    try:
        payload = json.loads(raw)
    except (UnicodeDecodeError, json.JSONDecodeError) as exc:
        raise SystemExit(f"invalid JSON payload: {exc}") from exc

    streams = payload.get("streams") if isinstance(payload, dict) else None
    if not isinstance(streams, dict) or len(streams) > 128:
        raise SystemExit("streams must be an object with at most 128 entries")

    validated: dict[str, str] = {}
    for name, value in streams.items():
        if not isinstance(name, str) or not NAME_RE.fullmatch(name):
            raise SystemExit("invalid stream name")
        if (
            not isinstance(value, str)
            or len(value) > 4096
            or any(ord(char) < 32 for char in value)
        ):
            raise SystemExit(f"invalid stream URL for {name}")
        parsed = urlsplit(value)
        if parsed.scheme.lower() not in {"rtsp", "rtsps"} or not parsed.hostname:
            raise SystemExit(f"only absolute RTSP URLs are allowed for {name}")
        validated[name] = value
    validated.setdefault("easypi_discovery", "rtsp://127.0.0.1:9/unavailable")

    lines = [
        "# Generated by EasyPi. Manual changes will be replaced.",
        "app:",
        "  modules: [api, ws, rtsp, mp4]",
        "api:",
        '  listen: "127.0.0.1:1984"',
    ]
    credentials_file = Path("/opt/go2rtc/api.env")
    if credentials_file.is_file() and not credentials_file.is_symlink():
        lines.extend(
            [
                '  username: "${GO2RTC_API_USERNAME}"',
                '  password: "${GO2RTC_API_PASSWORD}"',
                "  local_auth: true",
            ]
        )
    lines.extend(
        [
            "  allow_paths: [/, /api, /api/streams, /api/ws]",
            "rtsp:",
            '  listen: "127.0.0.1:8554"',
        ]
    )
    lines.extend(["log:", "  level: disabled", "streams:"])
    if validated:
        for name, value in sorted(validated.items()):
            lines.append(f"  {json.dumps(name)}: {json.dumps(value)}")
    else:
        lines[-1] = "streams: {}"

    target = Path(sys.argv[1])
    fd, tmp_name = tempfile.mkstemp(prefix=".go2rtc.", dir=str(target.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as handle:
            handle.write("\n".join(lines) + "\n")
            handle.flush()
            os.fsync(handle.fileno())
        os.chown(tmp_name, 0, grp.getgrnam("go2rtc").gr_gid)
        os.chmod(tmp_name, 0o640)
        os.replace(tmp_name, target)
    finally:
        try:
            os.unlink(tmp_name)
        except FileNotFoundError:
            pass


if __name__ == "__main__":
    main()
