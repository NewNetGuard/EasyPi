"""
EasyPi NetProtection - Blocklist Filter

High-performance domain blocklist filter using set-based lookups.
Loads domains from effective_blocklist.txt generated by BlocklistManager.

Features:
- Domain normalization (lowercase, punycode, trailing dot removal)
- Allowlist override support
- Atomic file reading with fallback
- Smart subdomain blocking with TLD awareness
- Statistics with overflow protection
"""

from __future__ import annotations

import logging
import time
import shutil
import tempfile
import json
import threading
from pathlib import Path
from typing import Optional, Set, Dict, Any
from dataclasses import dataclass
from ..time_utils import utc_now
from urllib.parse import urlparse

from ..config import get_settings
from ..list_files import lists_lock, write_text_atomic

logger = logging.getLogger(__name__)

# Maximum blocklist file size (50MB)
MAX_BLOCKLIST_SIZE_BYTES = 128 * 1024 * 1024  # effective list with HaGeZi PRO + full TIF is ~58MB/2.8M domains; 50MB was too low

# Statistics rollover threshold (prevent overflow)
STATS_ROLLOVER_THRESHOLD = 2**62

# Which list blocked a domain (see BlocklistFilter.block_source).
BLOCK_SOURCE_USER = "user"  # the user's own blacklist (user_blocklist.txt)
BLOCK_SOURCE_LIST = "list"  # the downloaded blocklists

# Common multi-part TLDs that should not be treated as blockable domains
# This prevents blocking "co.uk" from blocking all .co.uk sites
MULTI_PART_TLDS = frozenset({
    # UK
    'co.uk', 'org.uk', 'me.uk', 'net.uk', 'ac.uk', 'gov.uk', 'ltd.uk', 'plc.uk',
    # Australia
    'com.au', 'net.au', 'org.au', 'edu.au', 'gov.au', 'asn.au', 'id.au',
    # Brazil
    'com.br', 'net.br', 'org.br', 'gov.br', 'edu.br',
    # Japan
    'co.jp', 'or.jp', 'ne.jp', 'ac.jp', 'go.jp', 'ed.jp',
    # Germany
    'co.de',
    # India
    'co.in', 'net.in', 'org.in', 'gov.in', 'ac.in',
    # New Zealand
    'co.nz', 'net.nz', 'org.nz', 'govt.nz', 'ac.nz',
    # South Africa
    'co.za', 'org.za', 'net.za', 'gov.za', 'ac.za',
    # Russia
    'com.ru', 'org.ru', 'net.ru',
    # Generic
    'com.sg', 'com.hk', 'com.tw', 'com.mx', 'com.ar', 'com.co',
    'org.sg', 'org.hk', 'org.tw', 'org.mx', 'org.ar', 'org.co',
})

# Local/special domains that should never be blocked
LOCAL_DOMAINS = frozenset({
    'localhost',
    'localhost.localdomain',
    'local',
    'localdomain',
    'invalid',
    'test',
    'example',
    'example.com',
    'example.net',
    'example.org',
    # RFC 6762 - Multicast DNS
    'local',
    # Internal networks
    'home',
    'lan',
    'internal',
    'intranet',
    'corp',
    'private',
})


@dataclass
class BlocklistStats:
    """Blocklist filter statistics with overflow protection."""
    domains_loaded: int = 0
    allowlist_size: int = 0
    file_path: str = ""
    loaded_at: Optional[str] = None
    load_time_ms: float = 0.0
    lookups: int = 0
    hits: int = 0
    misses: int = 0
    allowlist_overrides: int = 0
    local_skips: int = 0
    
    def increment_lookups(self) -> None:
        """Increment lookups with rollover protection."""
        self.lookups += 1
        if self.lookups >= STATS_ROLLOVER_THRESHOLD:
            self._rollover()
    
    def increment_hits(self) -> None:
        """Increment hits with rollover protection."""
        self.hits += 1
    
    def increment_misses(self) -> None:
        """Increment misses with rollover protection."""
        self.misses += 1
    
    def increment_allowlist_overrides(self) -> None:
        """Increment allowlist overrides."""
        self.allowlist_overrides += 1
    
    def increment_local_skips(self) -> None:
        """Increment local domain skips."""
        self.local_skips += 1
    
    def _rollover(self) -> None:
        """Reset counters on overflow, preserving ratios."""
        logger.info("Statistics rollover triggered - resetting counters")
        # Keep ratio information by dividing by 1000
        self.lookups = self.lookups // 1000
        self.hits = self.hits // 1000
        self.misses = self.misses // 1000
        self.allowlist_overrides = self.allowlist_overrides // 1000
        self.local_skips = self.local_skips // 1000
    
    @property
    def hit_rate(self) -> float:
        if self.lookups == 0:
            return 0.0
        return (self.hits / self.lookups) * 100
    
    def reset(self) -> None:
        """Reset all counters."""
        self.lookups = 0
        self.hits = 0
        self.misses = 0
        self.allowlist_overrides = 0
        self.local_skips = 0
    
    def export(self) -> dict:
        """Export stats for external metrics systems."""
        return {
            "blocklist_domains_loaded": self.domains_loaded,
            "blocklist_allowlist_size": self.allowlist_size,
            "blocklist_lookups_total": self.lookups,
            "blocklist_hits_total": self.hits,
            "blocklist_misses_total": self.misses,
            "blocklist_allowlist_overrides_total": self.allowlist_overrides,
            "blocklist_local_skips_total": self.local_skips,
            "blocklist_hit_rate_percent": round(self.hit_rate, 2),
        }


def normalize_domain(domain: str) -> Optional[str]:
    """
    Normalize a domain name for consistent lookups.
    
    - Lowercase
    - Strip trailing dot
    - Convert IDN to punycode (ASCII)
    - Filter empty/invalid
    
    Returns None for invalid domains.
    """
    if not domain:
        return None
    
    # Basic cleanup
    normalized = domain.strip().lower()

    # Accept URL-like input (e.g. https://dnscheck.tools/path) and normalize to host
    if "://" in normalized:
        parsed = urlparse(normalized)
        normalized = (parsed.hostname or "").strip().lower()
    else:
        # Handle accidental path/userinfo/port in plain host input
        normalized = normalized.split("/", 1)[0]
        if "@" in normalized:
            normalized = normalized.rsplit("@", 1)[-1]
        if ":" in normalized:
            normalized = normalized.split(":", 1)[0]

    normalized = normalized.strip().rstrip('.')
    
    if not normalized:
        return None
    
    # Filter obviously invalid domains
    if len(normalized) > 253:  # Max DNS name length
        return None
    
    # Try IDN to punycode conversion
    try:
        # encode to punycode then decode to ASCII string
        normalized = normalized.encode('idna').decode('ascii')
    except (UnicodeError, UnicodeDecodeError):
        # If IDN conversion fails, keep original if it's valid ASCII
        if not normalized.isascii():
            return None
    
    return normalized


def is_local_domain(domain: str) -> bool:
    """Check if domain is a local/special domain that shouldn't be blocked."""
    if not domain:
        return True
    
    # Direct match
    if domain in LOCAL_DOMAINS:
        return True
    
    # Check suffix (e.g., "myhost.local")
    parts = domain.split('.')
    if parts[-1] in {'local', 'localhost', 'lan', 'home', 'internal', 'invalid', 'test'}:
        return True
    
    # RFC 1918 reverse DNS
    if domain.endswith('.in-addr.arpa') or domain.endswith('.ip6.arpa'):
        return True
    
    return False


class BlocklistFilter:
    """
    High-performance domain blocklist filter.
    
    Uses a set for O(1) lookups.
    Supports allowlist override and automatic reload.
    Supports switching between verified and custom blocklist.
    Supports user_blocklist.txt for custom domain blocks from UI.
    Supports instant reload via signal file (.lists_reload).
    """
    
    def __init__(self, data_dir: str | Path):
        self.data_dir = Path(data_dir)
        self.verified_file = self.data_dir / "verified_blocklist.txt"
        self.custom_file = self.data_dir / "custom_blocklist.txt"
        self.user_blocklist_file = self.data_dir / "user_blocklist.txt"  # UI blacklist
        self.config_file = self.data_dir / "blocklist_config.json"
        self.allowlist_file = self.data_dir / "allowlist.txt"
        self._reload_signal_file = self.data_dir / ".lists_reload"  # Signal for instant reload
        self._user_blocklist_meta_file = self.data_dir / "user_blocklist_meta.json"  # Hits metadata
        self._allowlist_meta_file = self.data_dir / "allowlist_meta.json"  # Allowlist hits metadata
        self._meta_lock = threading.Lock()  # Thread-safe meta file access
        
        # Which blocklist to use
        self._use_custom = False
        self._load_config()
        
        # Domain sets for O(1) lookups
        self._domains: Set[str] = set()
        self._allowlist: Set[str] = set()
        self._user_blocklist: Set[str] = set()  # User-added blocks from UI
        
        # Previous valid state for fallback
        self._previous_domains: Set[str] = set()
        
        # File modification tracking for auto-reload
        self._file_mtime: float = 0.0
        self._allowlist_mtime: float = 0.0
        self._user_blocklist_mtime: float = 0.0
        
        # Statistics
        self._stats = BlocklistStats()
        
        # Load blocklist (graceful - won't fail)
        self._load()
        self._load_allowlist()
        self._load_user_blocklist()
    
    def _load_config(self) -> None:
        """Load blocklist config (which file to use)."""
        if self.config_file.exists():
            try:
                import json
                with open(self.config_file, 'r') as f:
                    config = json.load(f)
                self._use_custom = config.get("use_custom", False)
            except Exception as e:
                logger.warning(f"Failed to load blocklist config: {e}")
                self._use_custom = False
    
    def _save_config(self) -> None:
        """Save blocklist config."""
        try:
            import json
            with open(self.config_file, 'w') as f:
                json.dump({"use_custom": self._use_custom}, f)
        except Exception as e:
            logger.error(f"Failed to save blocklist config: {e}")
    
    @property
    def blocklist_file(self) -> Path:
        """Get current blocklist file based on config."""
        if self._use_custom and self.custom_file.exists():
            return self.custom_file
        return self.verified_file
    
    @property
    def use_custom(self) -> bool:
        """Check if using custom blocklist."""
        return self._use_custom
    
    def set_use_custom(self, enabled: bool) -> bool:
        """
        Switch between verified and custom blocklist.
        
        Returns True if switched successfully.
        """
        if enabled and not self.custom_file.exists():
            logger.warning("Cannot enable custom blocklist: file not found")
            return False
        
        self._use_custom = enabled
        self._save_config()
        
        # Reload with new file
        self._file_mtime = 0  # Force reload
        self._load()
        
        logger.info(f"Switched to {'custom' if enabled else 'verified'} blocklist")
        return True
    
    def _load(self) -> bool:
        """
        Load domains from blocklist file with atomic read and fallback.
        
        Returns True if loaded successfully, False otherwise.
        Never throws - graceful degradation.
        """
        if not self.blocklist_file.exists():
            logger.info(f"Blocklist file not found: {self.blocklist_file} - starting with empty blocklist")
            self._domains = set()
            self._stats.domains_loaded = 0
            self._stats.loaded_at = utc_now().isoformat()
            return True  # Empty blocklist is valid
        
        # Check file size
        try:
            st = self.blocklist_file.stat()
            file_size = st.st_size
            if file_size > MAX_BLOCKLIST_SIZE_BYTES:
                logger.error(f"Blocklist file too large ({file_size} bytes > {MAX_BLOCKLIST_SIZE_BYTES}). "
                           "Using previous version or empty.")
                if self._previous_domains:
                    self._domains = self._previous_domains.copy()
                # Advance mtime so an oversized file isn't re-detected as "changed" on every
                # query (would cause a reload storm: this method runs on each DNS request).
                self._file_mtime = st.st_mtime
                return False
        except OSError as e:
            logger.error(f"Cannot stat blocklist file: {e}")
            return False
        
        start_time = time.monotonic()
        
        # Atomic read: copy to temp file first
        temp_file = None
        try:
            # Create temp copy for atomic read
            with tempfile.NamedTemporaryFile(mode='w', suffix='.txt', delete=False) as tmp:
                temp_file = Path(tmp.name)
                with open(self.blocklist_file, 'r', encoding='utf-8') as src:
                    shutil.copyfileobj(src, tmp)
            
            # Parse from temp file
            domains = set()
            line_count = 0
            error_count = 0
            
            with open(temp_file, 'r', encoding='utf-8') as f:
                for line in f:
                    line_count += 1
                    line = line.strip()
                    
                    # Skip empty lines and comments
                    if not line or line.startswith('#'):
                        continue
                    
                    # Normalize domain
                    normalized = normalize_domain(line)
                    if normalized is None:
                        error_count += 1
                        continue
                    
                    # Skip local/special domains
                    if is_local_domain(normalized):
                        continue
                    
                    # Skip multi-part TLDs (prevent blocking all of .co.uk)
                    if normalized in MULTI_PART_TLDS:
                        logger.debug(f"Skipping multi-part TLD: {normalized}")
                        continue
                    
                    domains.add(normalized)
            
            load_time = (time.monotonic() - start_time) * 1000
            
            # Save previous valid state before updating
            if self._domains:
                self._previous_domains = self._domains.copy()
            
            self._domains = domains
            self._file_mtime = self.blocklist_file.stat().st_mtime
            
            self._stats.domains_loaded = len(domains)
            self._stats.file_path = str(self.blocklist_file)
            self._stats.loaded_at = utc_now().isoformat()
            self._stats.load_time_ms = round(load_time, 2)
            
            logger.info(f"Loaded {len(domains):,} domains from blocklist in {load_time:.1f}ms "
                       f"({error_count} invalid entries skipped)")
            return True
            
        except Exception as e:
            logger.error(f"Failed to load blocklist: {e}")
            # Fallback to previous version
            if self._previous_domains:
                logger.warning("Falling back to previous blocklist version")
                self._domains = self._previous_domains.copy()
            return False
        finally:
            # Cleanup temp file
            if temp_file and temp_file.exists():
                try:
                    temp_file.unlink()
                except OSError:
                    pass
    
    def _load_allowlist(self) -> bool:
        """Load allowlist for override support."""
        if not self.allowlist_file.exists():
            logger.debug(f"Allowlist file not found: {self.allowlist_file}")
            self._allowlist = set()
            return True
        
        try:
            allowlist = set()
            with open(self.allowlist_file, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith('#'):
                        normalized = normalize_domain(line)
                        if normalized:
                            allowlist.add(normalized)
            
            self._allowlist = allowlist
            self._allowlist_mtime = self.allowlist_file.stat().st_mtime
            self._stats.allowlist_size = len(allowlist)
            
            if allowlist:
                logger.info(f"Loaded {len(allowlist):,} domains to allowlist")
            return True
            
        except Exception as e:
            logger.error(f"Failed to load allowlist: {e}")
            return False
    
    def _load_user_blocklist(self) -> bool:
        """Load user blocklist from UI (user_blocklist.txt)."""
        if not self.user_blocklist_file.exists():
            logger.debug(f"User blocklist file not found: {self.user_blocklist_file}")
            self._user_blocklist = set()
            return True
        
        try:
            user_blocklist = set()
            with open(self.user_blocklist_file, 'r', encoding='utf-8') as f:
                for line in f:
                    line = line.strip()
                    if line and not line.startswith('#'):
                        normalized = normalize_domain(line)
                        if normalized:
                            user_blocklist.add(normalized)
            
            self._user_blocklist = user_blocklist
            self._user_blocklist_mtime = self.user_blocklist_file.stat().st_mtime
            
            if user_blocklist:
                logger.info(f"Loaded {len(user_blocklist):,} domains to user blocklist")
            return True
            
        except Exception as e:
            logger.error(f"Failed to load user blocklist: {e}")
            return False
    
    def _increment_user_blocklist_hits(self, domain: str) -> None:
        """Increment hits counter for domain in user_blocklist_meta.json."""
        self._increment_meta_hits(self._user_blocklist_meta_file, domain)

    def _increment_meta_hits(self, meta_file: Path, domain: str) -> None:
        """Count one hit for a list entry, shared safely with the backend.

        The backend rewrites the same file when the user edits a list, so the
        read-change-write runs under the shared list lock and the write
        replaces the file in one step. An unreadable file is left alone
        rather than replaced with hit counts only, which would erase the
        comments and sources the user saved.
        """
        try:
            with self._meta_lock, lists_lock(self.data_dir):
                metadata: Dict[str, Any] = {}
                if meta_file.exists():
                    try:
                        with open(meta_file, 'r', encoding='utf-8') as f:
                            metadata = json.load(f)
                    except (json.JSONDecodeError, IOError) as e:
                        logger.debug(f"Skipping hit count, {meta_file.name} unreadable: {e}")
                        return

                if domain in metadata:
                    metadata[domain]["hits"] = metadata[domain].get("hits", 0) + 1
                else:
                    metadata[domain] = {
                        "addedAt": utc_now().isoformat(),
                        "hits": 1,
                    }

                write_text_atomic(
                    meta_file, json.dumps(metadata, indent=2), durable=False
                )
        except Exception as e:
            logger.debug(f"Failed to increment hits for {domain}: {e}")

    def _increment_allowlist_hits(self, domain: str) -> None:
        """Increment hits counter for a domain in allowlist_meta.json.

        Mirrors the user-blocklist hit tracking so the UI whitelist shows real
        per-domain usage instead of a constant 0.
        """
        self._increment_meta_hits(self._allowlist_meta_file, domain)

    def _check_reload_signal(self) -> bool:
        """Check if reload signal file exists and remove it."""
        if self._reload_signal_file.exists():
            try:
                self._reload_signal_file.unlink()
                logger.info("Lists reload signal received - forcing immediate reload")
                return True
            except Exception as e:
                logger.error(f"Failed to remove reload signal: {e}")
        return False
    
    def reload_if_changed(self) -> bool:
        """Reload blocklist and allowlist if files have been modified or signal received."""
        changed = False
        
        # Check for immediate reload signal first (from backend API)
        if self._check_reload_signal():
            logger.info("Reloading all lists due to signal...")
            self._load_allowlist()
            self._load_user_blocklist()
            return True
        
        # Check blocklist
        if self.blocklist_file.exists():
            try:
                current_mtime = self.blocklist_file.stat().st_mtime
                if current_mtime > self._file_mtime:
                    logger.info("Blocklist file changed, reloading...")
                    if self._load():
                        changed = True
            except OSError as e:
                logger.error(f"Error checking blocklist file: {e}")
        
        # Check allowlist
        if self.allowlist_file.exists():
            try:
                current_mtime = self.allowlist_file.stat().st_mtime
                if current_mtime > self._allowlist_mtime:
                    logger.info("Allowlist file changed, reloading...")
                    if self._load_allowlist():
                        changed = True
            except OSError as e:
                logger.error(f"Error checking allowlist file: {e}")
        
        # Check user blocklist
        if self.user_blocklist_file.exists():
            try:
                current_mtime = self.user_blocklist_file.stat().st_mtime
                if current_mtime > self._user_blocklist_mtime:
                    logger.info("User blocklist file changed, reloading...")
                    if self._load_user_blocklist():
                        changed = True
            except OSError as e:
                logger.error(f"Error checking user blocklist file: {e}")
        
        return changed
    
    def is_allowed(self, domain: str) -> bool:
        """
        Check if domain is explicitly allowed (in allowlist).
        
        Also checks parent domains for subdomain allowlisting.
        """
        if not self._allowlist:
            return False
        
        normalized = normalize_domain(domain)
        if not normalized:
            return False
        
        # Direct lookup
        if normalized in self._allowlist:
            self._increment_allowlist_hits(normalized)
            return True

        # Check parent domains
        parts = normalized.split('.')
        for i in range(1, len(parts) - 1):  # Don't check TLD alone
            parent = '.'.join(parts[i:])
            # Skip if parent is a multi-part TLD
            if parent in MULTI_PART_TLDS:
                continue
            if parent in self._allowlist:
                self._increment_allowlist_hits(parent)
                return True

        return False
    
    def is_blocked(self, domain: str, check_allowlist: bool = True) -> bool:
        """
        Check if domain is in blocklist or user blocklist.

        Args:
            domain: Domain to check
            check_allowlist: If True, allowlist can override blocklist

        Also checks parent domains for subdomain blocking,
        with awareness of multi-part TLDs.
        """
        return self.block_source(domain, check_allowlist=check_allowlist) is not None

    def block_source(self, domain: str, check_allowlist: bool = True) -> str | None:
        """Return which list blocks the domain: BLOCK_SOURCE_USER, BLOCK_SOURCE_LIST or None.

        The user's own blacklist and the downloaded blocklists are reported
        separately so the dashboard can tell the user who blocked a domain.
        """
        self._stats.increment_lookups()

        # Normalize domain
        normalized = normalize_domain(domain)
        if not normalized:
            self._stats.increment_misses()
            return None

        # Skip local/special domains
        if is_local_domain(normalized):
            self._stats.increment_local_skips()
            return None

        # Check allowlist first (if enabled)
        if check_allowlist and self.is_allowed(normalized):
            self._stats.increment_allowlist_overrides()
            return None

        # Check user blocklist (UI blacklist) - highest priority after allowlist
        if normalized in self._user_blocklist:
            self._stats.increment_hits()
            self._increment_user_blocklist_hits(normalized)
            logger.debug(f"Domain {normalized} blocked by user blocklist")
            return BLOCK_SOURCE_USER

        # Check user blocklist parent domains
        parts = normalized.split('.')
        for i in range(1, len(parts)):
            parent = '.'.join(parts[i:])
            if parent in MULTI_PART_TLDS:
                continue
            if '.' not in parent:
                continue
            if parent in self._user_blocklist:
                self._stats.increment_hits()
                self._increment_user_blocklist_hits(parent)
                logger.debug(f"Domain {normalized} blocked by user blocklist (parent: {parent})")
                return BLOCK_SOURCE_USER

        # Direct lookup in main blocklist
        if normalized in self._domains:
            self._stats.increment_hits()
            return BLOCK_SOURCE_LIST

        # Check parent domains (subdomain blocking)
        # But be careful not to block based on multi-part TLDs
        for i in range(1, len(parts)):
            parent = '.'.join(parts[i:])

            # Skip if parent is a multi-part TLD (e.g., co.uk)
            if parent in MULTI_PART_TLDS:
                continue

            # Skip single-part TLDs
            if '.' not in parent:
                continue

            if parent in self._domains:
                self._stats.increment_hits()
                return BLOCK_SOURCE_LIST

        self._stats.increment_misses()
        return None
    
    def add_to_allowlist(self, domain: str) -> bool:
        """Add domain to in-memory allowlist."""
        normalized = normalize_domain(domain)
        if not normalized:
            return False
        
        self._allowlist.add(normalized)
        self._stats.allowlist_size = len(self._allowlist)
        return True
    
    def remove_from_allowlist(self, domain: str) -> bool:
        """Remove domain from in-memory allowlist."""
        normalized = normalize_domain(domain)
        if not normalized:
            return False
        
        self._allowlist.discard(normalized)
        self._stats.allowlist_size = len(self._allowlist)
        return True
    
    def get_stats(self) -> dict:
        """Get filter statistics."""
        return {
            "domains_loaded": self._stats.domains_loaded,
            "allowlist_size": self._stats.allowlist_size,
            "file_path": self._stats.file_path,
            "loaded_at": self._stats.loaded_at,
            "load_time_ms": self._stats.load_time_ms,
            "lookups": self._stats.lookups,
            "hits": self._stats.hits,
            "misses": self._stats.misses,
            "allowlist_overrides": self._stats.allowlist_overrides,
            "local_skips": self._stats.local_skips,
            "hit_rate_percent": round(self._stats.hit_rate, 2),
        }
    
    def export_metrics(self) -> dict:
        """Export metrics for Prometheus/external systems."""
        return self._stats.export()
    
    def reset_stats(self) -> None:
        """Reset statistics counters."""
        self._stats.reset()
        logger.info("Blocklist filter statistics reset")
    
    @property
    def domain_count(self) -> int:
        """Number of domains in blocklist."""
        return len(self._domains)
    
    @property
    def allowlist_count(self) -> int:
        """Number of domains in allowlist."""
        return len(self._allowlist)
    
    @property
    def is_loaded(self) -> bool:
        """Check if blocklist is loaded (may be empty)."""
        return self._stats.loaded_at is not None


# Global filter instance
_filter: Optional[BlocklistFilter] = None


def get_blocklist_filter(data_dir: str | Path | None = None) -> BlocklistFilter:
    """Get or create the global blocklist filter."""
    global _filter
    
    if _filter is None:
        if data_dir is None:
            # Default data directory from central config
            data_dir = get_settings().NETPROTECTION_DATA_DIR
        _filter = BlocklistFilter(data_dir)
    
    return _filter


def reload_blocklist() -> bool:
    """Force reload the blocklist."""
    global _filter
    if _filter is not None:
        return _filter._load() and _filter._load_allowlist()
    return False
